// Security headers on every response. The CSP carries only directives that
// cannot break first-party or third-party scripts (Next, Stripe, analytics);
// there is deliberately no script-src. frame-ancestors on a page's response
// does not affect the srcdoc iframes that page renders itself
// (/reading/q/[token], admin previews), so those keep working.
const securityHeaders = (frame) => [
  {
    key: 'Content-Security-Policy',
    value: `frame-ancestors ${frame === 'DENY' ? "'none'" : "'self'"}; object-src 'none'; base-uri 'self'`,
  },
  { key: 'X-Frame-Options', value: frame },
  { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
  { key: 'X-Content-Type-Options', value: 'nosniff' },
  { key: 'Permissions-Policy', value: 'camera=(), microphone=(), geolocation=()' },
];

/** @type {import('next').NextConfig} */
const nextConfig = {
  async headers() {
    return [
      { source: '/:path*', headers: securityHeaders('DENY') },
      // The static book reader is framed by the admin Books page
      // (same origin), so it may be framed by this site only. Later
      // entries override earlier ones for the same header.
      { source: '/book/:path*', headers: securityHeaders('SAMEORIGIN') },
    ];
  },
  reactStrictMode: true,
  // Blog heroes generated by the marketing platform live in the Supabase
  // `marketing` storage bucket.
  images: {
    remotePatterns: [{ protocol: 'https', hostname: 'ntqmddmesgdquatodsyu.supabase.co', pathname: '/storage/v1/object/public/**' }],
  },
  // resvg ships a native binary the bundler cannot pack; load it from
  // node_modules (the writer agent's exhibit renderer). instrumentation.ts
  // (event subscribers) runs without a flag since Next 15.
  serverExternalPackages: ['@resvg/resvg-js'],
  experimental: {
    // Admin pages are force-dynamic; re-fetch on every soft navigation rather
    // than re-using a 30-second-old payload.
    staleTimes: { dynamic: 0 },
  },
}

module.exports = nextConfig
